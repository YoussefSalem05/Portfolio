import numpy as np
import matplotlib.pyplot as plt


class ScaraNewtonRaphson:
    """2-DOF SCARA Kinematics Solver using Newton-Raphson Numerical Method."""

    def __init__(self, L1=45.0, L2=50.0):
        self.L1 = L1
        self.L2 = L2

    def forward_kinematics(self, theta):
        """f(theta): Returns end-effector [x, y] position."""
        t1, t2 = theta
        x = self.L1 * np.cos(t1) + self.L2 * np.cos(t1 + t2)
        y = self.L1 * np.sin(t1) + self.L2 * np.sin(t1 + t2)
        return np.array([x, y])

    def jacobian(self, theta):
        """J(theta): Analytical Jacobian matrix for 2-DOF planar arm."""
        t1, t2 = theta
        dx_dt1 = -self.L1 * np.sin(t1) - self.L2 * np.sin(t1 + t2)
        dx_dt2 = -self.L2 * np.sin(t1 + t2)
        dy_dt1 = self.L1 * np.cos(t1) + self.L2 * np.cos(t1 + t2)
        dy_dt2 = self.L2 * np.cos(t1 + t2)

        return np.array([[dx_dt1, dx_dt2], [dy_dt1, dy_dt2]])

    def inverse_kinematics(self, target_pos, theta_guess, tol=1e-4, max_iter=100):
        """Newton-Raphson IK solver: theta_{i+1} = theta_i + J_pinv * (x_d - f(theta_i))"""
        theta_i = np.array(theta_guess, dtype=float)
        x_d = np.array(target_pos, dtype=float)

        for _ in range(max_iter):
            current_pos = self.forward_kinematics(theta_i)
            error = x_d - current_pos

            if np.linalg.norm(error) < tol:
                return theta_i, True

            J = self.jacobian(theta_i)
            J_pinv = np.linalg.pinv(J)  # Pseudoinverse handles singularities
            delta_theta = J_pinv @ error
            theta_i += delta_theta

        return theta_i, False


# =====================================================================
# INTEGRATED WORKFLOW
# =====================================================================

# 1. Initialize Robot (L1 = 45mm, L2 = 50mm)
robot = ScaraNewtonRaphson(L1=45, L2=50)

# 2. Define Joint Angle Ranges for Workspace Generation
theta1_deg = [0, 22.5, 45, 67.5, 90]
theta2_deg = [0, 22.5, 45, 67.5, 90]
theta1_grid = np.radians(theta1_deg)
theta2_grid = np.radians(theta2_deg)

# Data storage
target_x = []
target_y = []
recovered_angles = []
ik_success_list = []

# Initial guess for Newton-Raphson (start near zero rad)
q_guess = [0.1, 0.1]

print("Processing Workspace Points & Testing Newton-Raphson IK...\n")

# 3. Generate Target Workspace (FK) & Solve IK for each point
for t1 in theta1_grid:
    for t2 in theta2_grid:
        # Step A: FK to get target position (x_d, y_d)
        target = robot.forward_kinematics([t1, t2])
        target_x.append(target[0])
        target_y.append(target[1])

        # Step B: NR IK to recover angles from target position
        q_sol, success = robot.inverse_kinematics(target, theta_guess=q_guess)

        ik_success_list.append(success)
        if success:
            recovered_angles.append(q_sol)
            # Use current solution as initial guess for next iteration (warm start)
            q_guess = q_sol

print(
    f"Successfully solved IK for {sum(ik_success_list)} / {len(ik_success_list)} workspace points."
)

# Convert lists to numpy arrays
target_x = np.array(target_x)
target_y = np.array(target_y)


# =====================================================================
# VISUALIZATION
# =====================================================================

fig, ax = plt.subplots(figsize=(7, 7))

# Plot target workspace points generated by FK
ax.scatter(
    target_x,
    target_y,
    color="red",
    s=40,
    zorder=3,
    label="FK Target Grid Points",
)

# Overlay one robot arm pose (e.g., reaching for point #12 in the grid)
sample_idx = 12
sample_q = recovered_angles[sample_idx]

# Arm Joint Coordinates
x0, y0 = 0, 0
x1 = robot.L1 * np.cos(sample_q[0])
y1 = robot.L1 * np.sin(sample_q[0])
x2 = x1 + robot.L2 * np.cos(sample_q[0] + sample_q[1])
y2 = y1 + robot.L2 * np.sin(sample_q[0] + sample_q[1])

# Draw Links and Joints
ax.plot(
    [x0, x1, x2],
    [y0, y1, y2],
    "o-",
    color="blue",
    linewidth=3,
    markersize=8,
    markerfacecolor="black",
    label=f"Arm Pose (t1={np.degrees(sample_q[0]):.1f}°, t2={np.degrees(sample_q[1]):.1f}°)",
)

# Format Plot
ax.set_title("SCARA Workspace & Integrated Newton-Raphson IK")
ax.set_xlabel("X Axis (mm)")
ax.set_ylabel("Y Axis (mm)")
ax.grid(True, linestyle="--", alpha=0.7)
ax.axis("equal")
ax.legend(loc="upper left")

plt.show()